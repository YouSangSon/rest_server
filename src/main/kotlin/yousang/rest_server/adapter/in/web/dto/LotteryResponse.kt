/**
 * 로또 티켓 목록 응답
 */
data class LottoTicketsResponse(
    val tickets: List<LottoTicketResponse>,
    val totalCount: Int,
    val totalAmount: Long
) {
    companion object {
        fun from(tickets: List<LottoTicket>): LottoTicketsResponse {
            return LottoTicketsResponse(
                tickets = tickets.map { LottoTicketResponse.from(it) },
                totalCount = tickets.size,
                totalAmount = tickets.sumOf { it.price.toLong() }
            )
        }
    }
}

