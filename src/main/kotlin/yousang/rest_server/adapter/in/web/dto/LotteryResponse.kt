/**
 * 로또 티켓 응답
 */
data class LottoTicketResponse(
    val id: Long?,
    val userId: Long,
    val drawNumber: Int,
    val numbers: List<Int>,
    val isAutoGenerated: Boolean,
    val purchaseDate: LocalDateTime,
    val price: Int,
    val isWinningChecked: Boolean,
    val winningRank: Int?,
    val winningAmount: Long?,
    val isWinning: Boolean
) {
    companion object {
        fun from(ticket: LottoTicket): LottoTicketResponse {
            return LottoTicketResponse(
                id = ticket.id,
                userId = ticket.userId,
                drawNumber = ticket.drawNumber,
                numbers = ticket.numbers,
                isAutoGenerated = ticket.isAutoGenerated,
                purchaseDate = ticket.purchaseDate,
                price = ticket.price,
                isWinningChecked = ticket.isWinningChecked,
                winningRank = ticket.winningRank,
                winningAmount = ticket.winningAmount,
                isWinning = ticket.isWinning()
            )
        }
    }
}

