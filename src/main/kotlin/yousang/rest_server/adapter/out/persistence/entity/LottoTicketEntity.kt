package yousang.rest_server.adapter.out.persistence.entity

import jakarta.persistence.*
import yousang.rest_server.domain.model.LottoTicket
import java.time.LocalDateTime

/**
 * 로또 티켓 JPA 엔티티
 */
@Entity
@Table(name = "lotto_tickets")
data class LottoTicketEntity(
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    val id: Long? = null,

    @Column(nullable = false)
    val userId: Long,

    @Column(nullable = false)
    val drawNumber: Int,

    @Column(nullable = false, columnDefinition = "TEXT")
    val numbers: String, // 쉼표로 구분된 번호 (예: "1,2,3,4,5,6")

    @Column(nullable = false)
    val isAutoGenerated: Boolean,

    @Column(nullable = false)
    val purchaseDate: LocalDateTime = LocalDateTime.now(),

    @Column(nullable = false)
    val price: Int = 1000,

    @Column(nullable = false)
    val isWinningChecked: Boolean = false,

    @Column(nullable = true)
    val winningRank: Int? = null,

    @Column(nullable = true)
    val winningAmount: Long? = null
) {
    /**
     * JPA 엔티티를 도메인 모델로 변환
     */
    fun toDomain(): LottoTicket {
        return LottoTicket(
            id = id,
            userId = userId,
            drawNumber = drawNumber,
            numbers = numbers.split(",").map { it.toInt() },
            isAutoGenerated = isAutoGenerated,
            purchaseDate = purchaseDate,
            price = price,
            isWinningChecked = isWinningChecked,
            winningRank = winningRank,
            winningAmount = winningAmount
        )
    }

    companion object {
        /**
         * 도메인 모델을 JPA 엔티티로 변환
         */
        fun fromDomain(domain: LottoTicket): LottoTicketEntity {
            return LottoTicketEntity(
                id = domain.id,
                userId = domain.userId,
                drawNumber = domain.drawNumber,
                numbers = domain.numbers.joinToString(","),
                isAutoGenerated = domain.isAutoGenerated,
                purchaseDate = domain.purchaseDate,
                price = domain.price,
                isWinningChecked = domain.isWinningChecked,
                winningRank = domain.winningRank,
                winningAmount = domain.winningAmount
            )
        }
    }
}
