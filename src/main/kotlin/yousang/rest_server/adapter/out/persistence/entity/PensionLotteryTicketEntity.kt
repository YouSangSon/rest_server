package yousang.rest_server.adapter.out.persistence.entity

import jakarta.persistence.*
import yousang.rest_server.domain.model.PensionLotteryTicket
import java.time.LocalDateTime

/**
 * 연금복권 티켓 JPA 엔티티
 */
@Entity
@Table(name = "pension_lottery_tickets")
data class PensionLotteryTicketEntity(
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    val id: Long? = null,

    @Column(nullable = false)
    val userId: Long,

    @Column(nullable = false)
    val drawNumber: Int,

    @Column(nullable = false, name = "group_number")
    val group: Int, // 'group'은 SQL 예약어이므로 컬럼명 변경

    @Column(nullable = false)
    val number: Int,

    @Column(nullable = false)
    val isAutoGenerated: Boolean,

    @Column(nullable = false)
    val purchaseDate: LocalDateTime = LocalDateTime.now(),

    @Column(nullable = false)
    val price: Int = 1000,

    @Column(nullable = false)
    val isWinningChecked: Boolean = false,

    @Column(nullable = true)
    val winningRank: Int? = null,

    @Column(nullable = true)
    val winningAmount: Long? = null,

    @Column(nullable = true)
    val monthlyPension: Long? = null
) {
    /**
     * JPA 엔티티를 도메인 모델로 변환
     */
    fun toDomain(): PensionLotteryTicket {
        return PensionLotteryTicket(
            id = id,
            userId = userId,
            drawNumber = drawNumber,
            group = group,
            number = number,
            isAutoGenerated = isAutoGenerated,
            purchaseDate = purchaseDate,
            price = price,
            isWinningChecked = isWinningChecked,
            winningRank = winningRank,
            winningAmount = winningAmount,
            monthlyPension = monthlyPension
        )
    }

    companion object {
        /**
         * 도메인 모델을 JPA 엔티티로 변환
         */
        fun fromDomain(domain: PensionLotteryTicket): PensionLotteryTicketEntity {
            return PensionLotteryTicketEntity(
                id = domain.id,
                userId = domain.userId,
                drawNumber = domain.drawNumber,
                group = domain.group,
                number = domain.number,
                isAutoGenerated = domain.isAutoGenerated,
                purchaseDate = domain.purchaseDate,
                price = domain.price,
                isWinningChecked = domain.isWinningChecked,
                winningRank = domain.winningRank,
                winningAmount = domain.winningAmount,
                monthlyPension = domain.monthlyPension
            )
        }
    }
}
